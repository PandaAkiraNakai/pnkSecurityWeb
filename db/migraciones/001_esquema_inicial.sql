-- 001 · Esquema inicial de PNKSecurity en PostgreSQL (Unidad 3)
-- Migra el modelo de la versión PHP/MySQL (Script_BD/pnk_security.sql) con claves foráneas,
-- restricciones CHECK y tipos nativos. La ejecuta la cuenta dueña del esquema (pnk_owner);
-- la API se conecta con pnk_app, que recibe solo los permisos que usa (al final del archivo).

CREATE TABLE direcciones (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calle   varchar(100) NOT NULL,
  numero  varchar(15)  NOT NULL,
  comuna  varchar(100) NOT NULL,
  region  varchar(100)
);

CREATE TABLE restaurantes (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut           varchar(12)  NOT NULL UNIQUE,
  nombre        varchar(200) NOT NULL CHECK (btrim(nombre) <> ''),
  fono          varchar(45)  NOT NULL,
  email         varchar(254),
  foto          varchar(200),
  direccion_id  integer NOT NULL REFERENCES direcciones (id),
  creado        timestamptz NOT NULL DEFAULT now(),
  eliminado     timestamptz
);

CREATE TABLE cartas (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurante_id  integer NOT NULL REFERENCES restaurantes (id) ON DELETE CASCADE,
  nombre          varchar(45) NOT NULL,
  orden           integer,
  visible         boolean NOT NULL DEFAULT true,
  foto            varchar(200),
  eliminado       timestamptz
);

CREATE TABLE categorias (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carta_id  integer NOT NULL REFERENCES cartas (id) ON DELETE CASCADE,
  nombre    varchar(100) NOT NULL,
  visible   boolean NOT NULL DEFAULT false,
  orden     integer,
  eliminado timestamptz
);

CREATE TABLE items (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id   integer NOT NULL REFERENCES categorias (id) ON DELETE CASCADE,
  nombre         varchar(100) NOT NULL,
  descripcion    varchar(300),
  tiempo         varchar(100),
  observaciones  varchar(300),
  precio         integer NOT NULL CHECK (precio >= 0),
  visible        boolean NOT NULL DEFAULT false,
  destacado      boolean NOT NULL DEFAULT false,
  puntuacion     smallint NOT NULL DEFAULT 0 CHECK (puntuacion BETWEEN 0 AND 5),
  foto           varchar(200),
  orden          integer,
  eliminado      timestamptz
);

CREATE TABLE usuarios (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre             varchar(100) NOT NULL CHECK (btrim(nombre) <> ''),
  email              varchar(254) NOT NULL UNIQUE CHECK (email = lower(email) AND email LIKE '%_@_%'),
  password_hash      varchar(100) NOT NULL CHECK (password_hash LIKE '$2%'),
  activo             boolean  NOT NULL DEFAULT true,
  intentos_fallidos  smallint NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
  bloqueado_hasta    timestamptz,
  creado             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE comentarios (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurante_id  integer NOT NULL REFERENCES restaurantes (id) ON DELETE CASCADE,
  usuario_id      integer NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  texto           varchar(500) NOT NULL CHECK (char_length(btrim(texto)) BETWEEN 1 AND 500),
  creado          timestamptz NOT NULL DEFAULT now(),
  actualizado     timestamptz
);

CREATE INDEX comentarios_restaurante_idx ON comentarios (restaurante_id, creado DESC);
CREATE INDEX cartas_restaurante_idx ON cartas (restaurante_id);
CREATE INDEX categorias_carta_idx ON categorias (carta_id);
CREATE INDEX items_categoria_idx ON items (categoria_id);

-- Permisos mínimos de la cuenta de aplicación ---------------------------------------------
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO pnk_app;
-- La carta es de solo lectura para la API
GRANT SELECT ON direcciones, restaurantes, cartas, categorias, items TO pnk_app;
-- Usuarios: lee lo necesario para el login y solo puede actualizar el contador de intentos
GRANT SELECT (id, nombre, email, password_hash, activo, intentos_fallidos, bloqueado_hasta) ON usuarios TO pnk_app;
GRANT UPDATE (intentos_fallidos, bloqueado_hasta) ON usuarios TO pnk_app;
-- Comentarios: crea, lee y borra; al editar solo cambia el texto y la fecha de edición
GRANT SELECT, INSERT, DELETE ON comentarios TO pnk_app;
GRANT UPDATE (texto, actualizado) ON comentarios TO pnk_app;
GRANT USAGE ON SEQUENCE comentarios_id_seq TO pnk_app;
